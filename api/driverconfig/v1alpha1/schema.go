package v1alpha1

import (
	"encoding/json"
	"fmt"
	"slices"

	"github.com/google/jsonschema-go/jsonschema"
)

// schemaEnums pins the wire values independently of runtime implementation enums.
var schemaEnums = map[string][]any{
	"cpuDeviceMode": {CPUDeviceModeGrouped, CPUDeviceModeIndividual},
	"groupBy":       {GroupByNUMANode, GroupBySocket, GroupByMachine},
	"allocator":     {AllocatorCPUManager, AllocatorExternal},
}

// driverConfigSchemaComment is the generated schema's top-level "$comment".
const driverConfigSchemaComment = "Schema for driverConfig values. Derived from api/driverconfig/v1alpha1.Config. The fields bindAddress, exposePCIeRoots, and kubeletRootDir are not configurable via this schema — use healthzPort, args.exposePCIeRoots, and either the chart's top-level kubeletRootDir value or --kubelet-root-dir for direct binary use. Generated by 'make driverconfig-schema'; do not edit by hand."

// GenerateDriverConfigSchema builds the driver config JSON Schema from
// the public Config type, retaining legacy wire types and applying schemaEnums.
func GenerateDriverConfigSchema() ([]byte, error) {
	schema, err := jsonschema.For[Config](nil)
	if err != nil {
		return nil, fmt.Errorf("inferring schema from Config: %w", err)
	}

	// Pointers track omission in Go without broadening the legacy Helm schema.
	for _, prop := range schema.Properties {
		prop.Types = slices.DeleteFunc(prop.Types, func(t string) bool { return t == "null" })
		if len(prop.Types) == 1 {
			prop.Type = prop.Types[0]
			prop.Types = nil
		}
	}

	for jsonKey, enum := range schemaEnums {
		prop, ok := schema.Properties[jsonKey]
		if !ok {
			return nil, fmt.Errorf("schemaEnums has entry %q but Config has no matching field", jsonKey)
		}
		prop.Enum = enum
	}

	schema.Properties["apiVersion"] = &jsonschema.Schema{
		Type: "string",
		Enum: []any{APIVersion},
	}
	schema.PropertyOrder = append([]string{"apiVersion"}, schema.PropertyOrder...)

	schema.Schema = "https://json-schema.org/draft/2020-12/schema"
	schema.ID = "driverconfig.schema.json"
	schema.Comment = driverConfigSchemaComment

	out, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshaling schema: %w", err)
	}
	return append(out, '\n'), nil
}
